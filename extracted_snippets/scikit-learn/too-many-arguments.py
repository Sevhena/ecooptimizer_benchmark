def _sparse_fit(self, X, y, sample_weight, solver_type, kernel, random_seed):
    X.data = np.asarray(X.data, dtype=np.float64, order="C")
    X.sort_indices()

    kernel_type = self._sparse_kernels.index(kernel)

    libsvm_sparse.set_verbosity_wrap(self.verbose)

    (
        self.support_,
        self.support_vectors_,
        dual_coef_data,
        self.intercept_,
        self._n_support,
        self._probA,
        self._probB,
        self.fit_status_,
        self._num_iter,
    ) = libsvm_sparse.libsvm_sparse_train(
        X.shape[1],
        X.data,
        X.indices,
        X.indptr,
        y,
        solver_type,
        kernel_type,
        self.degree,
        self._gamma,
        self.coef0,
        self.tol,
        self.C,
        getattr(self, "class_weight_", np.empty(0)),
        sample_weight,
        self.nu,
        self.cache_size,
        self.epsilon,
        int(self.shrinking),
        int(self.probability),
        self.max_iter,
        random_seed,
    )

    self._warn_from_fit_status()

    if hasattr(self, "classes_"):
        n_class = len(self.classes_) - 1
    else:  # regression
        n_class = 1
    n_SV = self.support_vectors_.shape[0]

    dual_coef_indices = np.tile(np.arange(n_SV), n_class)
    if not n_SV:
        self.dual_coef_ = sp.csr_matrix([])
    else:
        dual_coef_indptr = np.arange(
            0, dual_coef_indices.size + 1, dual_coef_indices.size / n_class
        )
        self.dual_coef_ = sp.csr_matrix(
            (dual_coef_data, dual_coef_indices, dual_coef_indptr), (n_class, n_SV)
        )


